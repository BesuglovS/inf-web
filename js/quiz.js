    function shuffle(arr) {
        var a = arr.slice();
        for (var i = a.length - 1; i > 0; i--) {
            var j = Math.floor(Math.random() * (i + 1));
            var tmp = a[i];
            a[i] = a[j];
            a[j] = tmp;
        }
        return a;
    }

    function initQuiz(container) {
        var topicId = container.getAttribute('data-topic');
        if (!topicId) return;

        var questions = QUIZ_DATA[topicId];
        if (!questions || questions.length === 0) {
            container.innerHTML = '<p class="quiz-empty">Вопросы пока не добавлены.</p>';
            return;
        }
        buildQuiz(container, questions);
    }

    function buildQuiz(container, rawQuestions) {
        var questions = shuffle(rawQuestions);
        var shuffledOptions = [];
        for (var i = 0; i < questions.length; i++) {
            var q = questions[i];
            var indices = [0, 1, 2];
            indices = shuffle(indices);
            var newCorrect = indices.indexOf(q.answer);
            var opts = [];
            for (var j = 0; j < indices.length; j++) {
                opts.push(q.options[indices[j]]);
            }
            shuffledOptions.push({
                q: q.q,
                options: opts,
                correct: newCorrect,
                explanation: q.explanation
            });
        }

        var state = {
            current: 0,
            total: shuffledOptions.length,
            answers: [],
            answered: false,
            finished: false
        };

        container.innerHTML = '';
        var header = document.createElement('div');
        header.className = 'quiz-header';
        header.innerHTML = '<h4>\u{1F9E0} \u041F\u0440\u043E\u0432\u0435\u0440\u044C \u0441\u0432\u043E\u0438 \u0437\u043D\u0430\u043D\u0438\u044F</h4>';
        container.appendChild(header);

        var counter = document.createElement('div');
        counter.className = 'quiz-counter';
        container.appendChild(counter);

        var body = document.createElement('div');
        body.className = 'quiz-body';
        container.appendChild(body);

        var nav = document.createElement('div');
        nav.className = 'quiz-nav';
        container.appendChild(nav);

        var result = document.createElement('div');
        result.className = 'quiz-final-result';
        container.appendChild(result);

        function render() {
            if (state.finished) {
                showResults();
                return;
            }

            var q = shuffledOptions[state.current];
            var num = state.current + 1;

            counter.textContent = '\u0412\u043E\u043F\u0440\u043E\u0441 ' + num + ' \u0438\u0437 ' + state.total;

            var html = '<p class="quiz-question-text">' + escapeHTML(q.q) + '</p>';
            html += '<div class="quiz-options">';
            for (var i = 0; i < q.options.length; i++) {
                var checked = state.answers[state.current] === i ? ' checked' : '';
                var cls = '';
                if (state.answered) {
                    if (i === q.correct) {
                        cls = ' correct';
                    } else if (state.answers[state.current] === i) {
                        cls = ' wrong';
                    }
                }
                html += '<label class="quiz-option' + cls + '">';
                html += '<input type="radio" name="dq" value="' + i + '"' + checked + '>';
                html += '<span class="quiz-option-letter">' + String.fromCharCode(65 + i) + '</span> ';
                html += escapeHTML(q.options[i]);
                if (state.answered && i === q.correct) {
                    html += ' <span class="quiz-check">\u2714</span>';
                } else if (state.answered && state.answers[state.current] === i && i !== q.correct) {
                    html += ' <span class="quiz-cross">\u2718</span>';
                }
                html += '</label>';
            }
            html += '</div>';

            if (state.answered) {
                var isCorrect = state.answers[state.current] === q.correct;
                html += '<div class="quiz-explanation quiz-explanation-' + (isCorrect ? 'correct' : 'wrong') + '">';
                if (isCorrect) {
                    html += '<span class="quiz-explanation-icon">\u2705</span> \u041F\u0440\u0430\u0432\u0438\u043B\u044C\u043D\u043E!';
                } else {
                    html += '<span class="quiz-explanation-icon">\u274C</span> \u041D\u0435\u043F\u0440\u0430\u0432\u0438\u043B\u044C\u043D\u043E.';
                }
                html += ' ' + escapeHTML(q.explanation);
                html += '</div>';
            }

            body.innerHTML = html;

            var navHtml = '';
            if (state.current > 0) {
                navHtml += '<button class="btn quiz-btn-prev" type="button">&larr; \u041D\u0430\u0437\u0430\u0434</button>';
            }
            if (state.answered) {
                if (state.current < state.total - 1) {
                    navHtml += '<button class="btn quiz-btn-next" type="button">\u0414\u0430\u043B\u0435\u0435 &rarr;</button>';
                } else {
                    navHtml += '<button class="btn quiz-btn-finish" type="button">\u0417\u0430\u0432\u0435\u0440\u0448\u0438\u0442\u044C \u0442\u0435\u0441\u0442</button>';
                }
            }
            nav.innerHTML = navHtml;

            var prevBtn = nav.querySelector('.quiz-btn-prev');
            var nextBtn = nav.querySelector('.quiz-btn-next');
            var finishBtn = nav.querySelector('.quiz-btn-finish');

            if (prevBtn) {
                prevBtn.addEventListener('click', function() {
                    state.current--;
                    state.answered = true;
                    render();
                });
            }
            if (nextBtn) {
                nextBtn.addEventListener('click', function() {
                    state.current++;
                    state.answered = false;
                    render();
                });
            }
            if (finishBtn) {
                finishBtn.addEventListener('click', function() {
                    state.finished = true;
                    render();
                });
            }

            if (!state.answered) {
                var radios = body.querySelectorAll('input[name="dq"]');
                for (var r = 0; r < radios.length; r++) {
                    radios[r].addEventListener('change', function() {
                        var val = parseInt(this.value);
                        state.answers[state.current] = val;
                        state.answered = true;
                        render();
                    });
                }
            }
        }

        function showResults() {
            header.style.display = 'none';
            counter.style.display = 'none';
            body.style.display = 'none';
            nav.style.display = 'none';

            var score = 0;
            var wrongList = [];
            for (var i = 0; i < shuffledOptions.length; i++) {
                var q = shuffledOptions[i];
                if (state.answers[i] === q.correct) {
                    score++;
                } else {
                    wrongList.push({
                        question: q.q,
                        correctAnswer: q.options[q.correct]
                    });
                }
            }

            var total = state.total;
            var html = '<div class="quiz-result-card">';
            html += '<h4>\u0420\u0435\u0437\u0443\u043B\u044C\u0442\u0430\u0442\u044B \u0442\u0435\u0441\u0442\u0430</h4>';
            html += '<div class="quiz-score">';
            html += '<span class="quiz-score-num">' + score + '</span>';
            html += '<span class="quiz-score-sep"> / </span>';
            html += '<span class="quiz-score-total">' + total + '</span>';
            html += '</div>';

            var pct = Math.round((score / total) * 100);
            html += '<div class="quiz-score-bar"><div class="quiz-score-fill" style="width:' + pct + '%"></div></div>';

            if (score === total) {
                html += '<p class="quiz-verdict quiz-verdict-excellent">\u041E\u0442\u043B\u0438\u0447\u043D\u043E! \u0412\u0441\u0435 \u043E\u0442\u0432\u0435\u0442\u044B \u043F\u0440\u0430\u0432\u0438\u043B\u044C\u043D\u044B\u0435!</p>';
            } else if (pct >= 60) {
                html += '<p class="quiz-verdict quiz-verdict-good">\u0425\u043E\u0440\u043E\u0448\u0438\u0439 \u0440\u0435\u0437\u0443\u043B\u044C\u0442\u0430\u0442! \u0415\u0441\u0442\u044C \u043D\u0430\u0434 \u0447\u0435\u043C \u043F\u043E\u0440\u0430\u0431\u043E\u0442\u0430\u0442\u044C.</p>';
            } else {
                html += '<p class="quiz-verdict quiz-verdict-low">\u0420\u0435\u043A\u043E\u043C\u0435\u043D\u0434\u0443\u0435\u0442\u0441\u044F \u043F\u043E\u0432\u0442\u043E\u0440\u0438\u0442\u044C \u043C\u0430\u0442\u0435\u0440\u0438\u0430\u043B.</p>';
            }

            if (wrongList.length > 0) {
                html += '<div class="quiz-wrong-list">';
                html += '<h5>\u041F\u0440\u0430\u0432\u0438\u043B\u044C\u043D\u044B\u0435 \u043E\u0442\u0432\u0435\u0442\u044B \u043D\u0430 \u043E\u0448\u0438\u0431\u043E\u0447\u043D\u044B\u0435 \u0432\u043E\u043F\u0440\u043E\u0441\u044B:</h5>';
                for (var w = 0; w < wrongList.length; w++) {
                    html += '<div class="quiz-wrong-item">';
                    html += '<p class="quiz-wrong-q">' + escapeHTML(wrongList[w].question) + '</p>';
                    html += '<p class="quiz-wrong-a">' + escapeHTML(wrongList[w].correctAnswer) + '</p>';
                    html += '</div>';
                }
                html += '</div>';
            }

            html += '<button class="btn quiz-btn-retry" type="button">\u041F\u0440\u043E\u0439\u0442\u0438 \u0435\u0449\u0451 \u0440\u0430\u0437</button>';
            html += '</div>';

            result.innerHTML = html;

            var retryBtn = result.querySelector('.quiz-btn-retry');
            retryBtn.addEventListener('click', function() {
                initQuiz(container);
            });
        }

        render();
    }

    document.addEventListener('DOMContentLoaded', function() {
        var containers = document.querySelectorAll('.dynamic-quiz');
        for (var i = 0; i < containers.length; i++) {
            initQuiz(containers[i]);
        }
    });
